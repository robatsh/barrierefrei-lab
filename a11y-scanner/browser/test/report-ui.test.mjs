import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import axe from 'axe-core';

test('report UI: pagination, filters, manual notes, JSON export and accessible responsive layout', async t => {
  const ui = new URL('../../desktop/ui/', import.meta.url);
  const server = createServer(async (req, res) => {
    const files = { '/': ['index.html', 'text/html'], '/app.js': ['app.js', 'application/javascript'], '/style.css': ['style.css', 'text/css'] };
    files['/i18n.js'] = ['i18n.js', 'application/javascript'];
    files['/references.js'] = ['references.js', 'application/javascript'];
    files['/locales/de.js'] = ['locales/de.js', 'application/javascript'];
    const file = files[req.url];
    if (!file) { res.writeHead(404).end(); return; }
    res.writeHead(200, { 'content-type': file[1] }); res.end(await readFile(new URL(file[0], ui)));
  });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => new Promise(resolve => server.close(resolve)));
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1180, height: 850 } });
  const report = JSON.parse(await readFile(new URL('../../examples/report.json', import.meta.url), 'utf8'));
  const sampleNode = report.pages.flatMap(p => p.violations).flatMap(r => r.nodes)[0];
  sampleNode.html = '<img id="hero-image" name="homepage-hero" alt="Startseitenmotiv" src="/hero.png">';
  sampleNode.target = ['#hero-image'];
  // Exercise more than one page of results without another network scan.
  report.pages.push(...report.pages.map(p => ({ ...p, url: `${p.url}?copy=1` })));
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(r => { window.__TAURI__ = { core: { invoke: async command => {
    if (command === 'scan_website') {
      if (window.__holdScan) await new Promise(resolve => { window.__finishScan = resolve; });
      return structuredClone(r);
    }
    throw new Error('Unexpected command');
  } } }; }, report);
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  assert.equal(await page.locator('footer').count(), 0);
  assert.equal(await page.locator('#storage-status').innerText(), '');
  await page.locator('.app-nav [data-view=scan]').click();
  await page.locator('#url').fill('https://example.org');
  await page.evaluate(() => { window.__holdScan = true; });
  await page.locator('#start').click();
  await page.locator('#scan-progress').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#scan-form').getAttribute('aria-busy'), 'true');
  assert.equal(await page.locator('#start').isDisabled(), true);
  assert.equal(await page.locator('[role=progressbar]').getAttribute('aria-valuenow'), null);
  await page.waitForFunction(() => document.getElementById('scan-elapsed').textContent !== '0:00');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.scan-progress-track span').evaluate(node => getComputedStyle(node).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  assert.equal(await page.locator('.scan-progress-track span').evaluate(node => getComputedStyle(node).animationName), 'scan-sweep');
  await page.evaluate(() => { window.__holdScan = false; window.__finishScan(); });
  await page.locator('#dashboard').waitFor();
  assert.equal(await page.locator('#scan-progress').isHidden(), true);
  assert.equal(await page.locator('#scan-form').getAttribute('aria-busy'), null);
  assert.equal(await page.locator('#start').isDisabled(), false);
  await page.locator('.app-nav [data-view=improvements]').click();
  const affected = page.locator('#tasks .element-card').filter({ hasText: '#hero-image' }).first();
  await affected.locator('xpath=ancestor::details[1]').evaluate(node => { node.open = true; });
  assert.equal(await affected.locator('h4').innerText(), '<img> #hero-image');
  assert.match(await affected.innerText(), /Name: homepage-hero/);
  assert.match(await affected.innerText(), /Startseitenmotiv/);
  assert.equal(await affected.locator('.element-location code').innerText(), '#hero-image');
  assert.equal(await affected.locator('img').count(), 0, 'scanned HTML stays inert');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1180, height: 850 });
  assert.ok(await page.locator('#tasks a[href="https://www.w3.org/WAI/tutorials/images/decision-tree/"]').count() > 0);
  assert.ok(await page.locator('#tasks a[href="https://developer.mozilla.org/en-US/docs/Web/HTML/Reference/Elements/img"]').count() > 0);
  assert.equal(await page.locator('#tasks a').first().getAttribute('rel'), 'noopener noreferrer');
  await page.getByText('Technische Befunde nach Seite', { exact: true }).click();
  await page.locator('#results').waitFor({ state: 'visible' });
  assert.equal(await page.locator('.page').count(), 5);
  assert.equal(await page.locator('.page[open]').count(), 0);
  await page.locator('#next').click();
  assert.equal(await page.locator('.page').count(), 3);
  await page.locator('#search').fill('image-alt');
  assert.ok(await page.locator('.page').count() > 0);
  await page.locator('#filter').selectOption('incomplete');
  assert.equal(await page.locator('.finding:not(.review)').count(), 0);
  await page.locator('#search').fill('');
  await page.locator('#filter').selectOption('all');
  assert.equal(await page.locator('.criterion').count(), 10);
  await page.locator('.app-nav [data-view=checklist]').click();
  await page.getByText(/Vollst.*ndiger.*Nachweise/).click();
  await page.locator('#standard-filter').selectOption('WCAG 2.1');
  await page.locator('#criteria-search').fill('2.1.1');
  await page.locator('.criterion > summary').click();
  await page.locator('.criterion select').selectOption('passed');
  assert.equal(await page.locator('.criterion select').inputValue(), 'unreviewed');
  await page.locator('.criterion textarea').fill('Tastatur: alle Bedienwege der Stichprobe geprüft.');
  await page.locator('.criterion select').selectOption('passed');
  assert.match(await page.locator('.criterion > summary').innerText(), /Manuell erfüllt/);
  const downloadPromise = page.waitForEvent('download'); await page.locator('#export-json').click();
  const downloaded = await downloadPromise;
  const saved = JSON.parse(await readFile(await downloaded.path(), 'utf8'));
  assert.equal(saved.coverage.find(c => c.id === '2.1.1').status, 'passed');
  assert.match(saved.coverage.find(c => c.id === '2.1.1').notes, /Tastatur/);
  await page.locator('#criteria-search').fill('1.1.1');
  await page.locator('.criterion > summary').click();
  await page.locator('.criterion textarea').fill('Kein Überschreiben automatischer Fehler.');
  await page.locator('.criterion select').selectOption('passed');
  assert.equal(await page.locator('.criterion select').inputValue(), 'failed');
  await page.locator('#criteria-search').fill('');
  await page.locator('#standard-filter').selectOption('all');
  await page.locator('.app-nav [data-view=improvements]').click();
  await page.locator('#tasks select').first().selectOption('review');
  await page.reload();
  await page.locator('[data-screen=projects]').waitFor();
  assert.equal(await page.locator('.app-nav [aria-current=page]').getAttribute('data-view'), 'projects');
  assert.match(await page.locator('#active-project').innerText(), /Projekt geladen/);
  await page.locator('.app-nav [data-view=overview]').click();
  await page.locator('#dashboard').waitFor();
  assert.match(await page.locator('#task-progress').innerText(), /1 von/);
  await page.locator('.app-nav [data-view=checklist]').click();
  await page.locator('#guided-checks textarea').first().fill('Startseite mit Tab und Enter bedient.');
  await page.locator('#guided-checks select').first().selectOption('passed');
  await page.reload();
  await page.locator('.app-nav [data-view=checklist]').click();
  assert.equal(await page.locator('#guided-checks select').first().inputValue(), 'passed');
  await page.locator('.app-nav [data-view=scan]').click();
  await page.locator('#start').click();
  await page.locator('#dashboard').waitFor();
  assert.match(await page.locator('#comparison').innerText(), /weiterhin vorhanden/);
  await page.locator('.app-nav [data-view=checklist]').click();
  assert.equal(await page.locator('#guided-checks select').first().inputValue(), 'open');
  await page.locator('.app-nav [data-view=overview]').click();
  await page.evaluate(axe.source);
  const audit = await page.evaluate(() => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }));
  assert.deepEqual(audit.violations.map(r => r.id), []);
  await mkdir(new URL('../../docs/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../../docs/report-ui.png', import.meta.url)), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no horizontal page scrolling');
  await page.locator('.app-nav [data-view=projects]').click();
  assert.equal(await page.locator('.project-card').count(), 1);
  const firstId = await page.locator('.project-card').getAttribute('data-project-id');
  await page.locator('#project-name').fill('Zweite Website');
  await page.locator('#project-url').fill('https://second.example/');
  await page.locator('#project-form button').click();
  assert.match(await page.locator('#active-project').innerText(), /Zweite Website/);
  assert.match(await page.locator('#active-project').innerText(), /https:\/\/second.example\//);
  assert.equal(await page.locator('#url').inputValue(), 'https://second.example/');
  await page.locator('#start').click();
  await page.locator('#dashboard').waitFor();
  assert.match(await page.locator('#task-progress').innerText(), /0 von/);
  await page.locator('.app-nav [data-view=improvements]').click();
  await page.locator('#tasks select').first().selectOption('working');
  await page.locator('.app-nav [data-view=projects]').click();
  assert.equal(await page.locator('.project-card').count(), 2);
  await page.locator(`[data-project-id="${firstId}"]`).getByRole('button', {name:'Projekt öffnen'}).click();
  assert.match(await page.locator('#task-progress').innerText(), /1 von/);
  await page.locator('.app-nav [data-view=projects]').click();
  const second = page.locator('.project-card').filter({has:page.getByRole('heading', {name:'Zweite Website'})});
  await second.getByRole('button', {name:'Projekt öffnen'}).click();
  await page.locator('.app-nav [data-view=improvements]').click();
  assert.equal(await page.locator('#tasks select').first().inputValue(), 'working');
  await page.locator('.app-nav [data-view=projects]').click();
  await second.getByRole('button', {name:'Projekt löschen'}).click();
  await page.locator('#cancel-delete').click();
  assert.equal(await page.locator('.project-card').count(), 2);
  await second.getByRole('button', {name:'Projekt löschen'}).click();
  await page.locator('#confirm-delete').click();
  assert.equal(await page.locator('.project-card').count(), 1);
  await page.reload();
  await page.locator('.app-nav [data-view=projects]').click();
  assert.equal(await page.locator('.project-card').count(), 1);
  assert.equal(await page.evaluate(() => localStorage.getItem('a11y-workspace-v1')), null);
  await page.locator('.project-card').getByRole('button', {name:'Projekt löschen'}).click();
  await page.locator('#confirm-delete').click();
  assert.equal(await page.locator('.project-card').count(), 0);
  await page.reload();
  assert.equal(await page.locator('.project-card').count(), 0);
  await page.locator('[data-screen=projects]').waitFor();
  assert.match(await page.locator('#active-project').innerText(), /Kein Projekt/);
  await page.evaluate(axe.source);
  const projectsAudit = await page.evaluate(() => window.axe.run(document));
  assert.deepEqual(projectsAudit.violations.map(r => r.id), []);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1180, height: 850 });
  await page.locator('#project-name').fill('Meine Website');
  await page.locator('#project-url').fill('https://example.org');
  await page.locator('#project-form button').click();
  await page.locator('.app-nav [data-view=projects]').click();
  await page.screenshot({ path: fileURLToPath(new URL('../../docs/projects-ui.png', import.meta.url)), fullPage: true });
  for (const view of ['scan', 'overview', 'improvements', 'checklist', 'projects']) {
    await page.locator(`.app-nav [data-view=${view}]`).click();
    const audit = await page.evaluate(() => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }));
    assert.deepEqual(audit.violations.map(r => r.id), [], `${view}: accessible layout and contrast`);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${view}: no horizontal scrolling`);
    await page.setViewportSize({ width: 1180, height: 850 });
  }
  // The single-report format is migrated without losing manual notes.
  await page.evaluate(r => {
    localStorage.removeItem('a11y-projects-v2');
    localStorage.setItem('a11y-workspace-v1', JSON.stringify(r));
  }, saved);
  await page.reload();
  await page.locator('.app-nav [data-view=projects]').click();
  assert.equal(await page.locator('.project-card').count(), 1);
  const migrated = await page.evaluate(() => JSON.parse(localStorage.getItem('a11y-projects-v2')));
  assert.equal(migrated.projects[0].report.coverage.find(c => c.id === '2.1.1').status, 'passed');
  assert.equal(await page.evaluate(() => localStorage.getItem('a11y-workspace-v1')), null);
  await page.locator('.app-nav [data-view=scan]').click();
  await page.evaluate(() => { window.__TAURI__.core.invoke = async () => { throw new Error('Test scan failure'); }; });
  await page.locator('#start').click();
  await page.locator('#error').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#scan-progress').isHidden(), true);
  assert.equal(await page.locator('#start').isDisabled(), false);
  assert.equal(await page.locator('#scan-form').getAttribute('aria-busy'), null);
  assert.deepEqual(errors, []);
});
